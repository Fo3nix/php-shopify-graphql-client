<?php

namespace Fo3nix\ShopifyGraphQL\ShopifyAdmin202604;

use GraphQL\SchemaObject\ArgumentsObject;

class ShopifyRootMutationAppUsageRecordCreateArgumentsObject extends ArgumentsObject
{
    const REQUIRED = ["subscriptionLineItemId", "price", "description"];

    protected $subscriptionLineItemId;
    protected $price;
    protected $description;
    protected $idempotencyKey;

    /**
     * The ID of the app subscription line item to create the usage record under. This app subscription line item must have a usage pricing plan.
     */
    public function setSubscriptionLineItemId($subscriptionLineItemId): static
    {
        $this->subscriptionLineItemId = $subscriptionLineItemId;

        return $this;
    }

    /**
     * The price of the app usage record.
     */
    public function setPrice(ShopifyMoneyInputInputObject $shopifyMoneyInputInputObject): static
    {
        $this->price = $shopifyMoneyInputInputObject;

        return $this;
    }

    /**
     * The description of the app usage record.
     */
    public function setDescription($description): static
    {
        $this->description = $description;

        return $this;
    }

    /**
     * A unique key generated by the client to avoid duplicate charges. Maximum length of 255 characters.
     */
    public function setIdempotencyKey($idempotencyKey): static
    {
        $this->idempotencyKey = $idempotencyKey;

        return $this;
    }
}
