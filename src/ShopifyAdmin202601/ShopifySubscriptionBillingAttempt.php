<?php

namespace Fo3nix\ShopifyGraphQL\ShopifyAdmin202601;

use Carbon\Carbon;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202601\ShopifyOrder;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202601\ShopifySubscriptionBillingAttemptProcessingErrorHydrator;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202601\ShopifySubscriptionBillingAttemptProcessingError;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202601\ShopifySubscriptionContract;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202601\ShopifyOrderTransactionConnection;

/**
 * A record of an execution of the subscription billing process. Billing attempts use idempotency keys to avoid duplicate order creation.
 *
 * When a billing attempt completes successfully, it creates an [`Order`](https://shopify.dev/docs/api/admin-graphql/latest/objects/Order). The attempt includes associated payment transactions and any errors that occur during billing. If 3D Secure authentication is required, the `nextActionUrl` field provides the redirect URL for customer verification.
 */
class ShopifySubscriptionBillingAttempt implements ShopifyNode
{
    protected $completedAt;
    protected $createdAt;
    protected $errorCode;
    protected $errorMessage;
    protected $id;
    protected $idempotencyKey;
    protected $nextActionUrl;
    protected $order;
    protected $originTime;
    protected $paymentGroupId;
    protected $paymentSessionId;
    protected $processingError;
    protected $ready;
    protected $respectInventoryPolicy;
    protected $subscriptionContract;
    protected $transactions;

    
    /**
     * The date and time when the billing attempt was completed.
     *
     * @return Carbon
     */
    public function getCompletedAt(): ?Carbon
    {
        return $this->completedAt;
    }

    
    /**
     * The date and time when the billing attempt was created.
     *
     * @return Carbon
     */
    public function getCreatedAt(): ?Carbon
    {
        return $this->createdAt;
    }

    
    /**
     * A code corresponding to a payment error during processing.
     *
     * @return string A ShopifySubscriptionBillingAttemptErrorCodeEnumObject value
     */
    public function getErrorCode(): ?string
    {
        return $this->errorCode;
    }

    
    /**
     * A message describing a payment error during processing.
     *
     * @return string
     */
    public function getErrorMessage(): ?string
    {
        return $this->errorMessage;
    }

    
    /**
     * A globally-unique ID.
     *
     * @return string
     */
    public function getId(): ?string
    {
        return $this->id;
    }

    
    /**
     * A unique key generated by the client to avoid duplicate payments.
     *
     * @return string
     */
    public function getIdempotencyKey(): ?string
    {
        return $this->idempotencyKey;
    }

    
    /**
     * The URL where the customer needs to be redirected so they can complete the 3D Secure payment flow.
     *
     * @return string
     */
    public function getNextActionUrl(): mixed
    {
        return $this->nextActionUrl;
    }

    
    /**
     * The result of this billing attempt if completed successfully.
     *
     * @return ShopifyOrder
     */
    public function getOrder(): ?ShopifyOrder
    {
        return $this->order;
    }

    
    /**
     * The date and time used to calculate fulfillment intervals for a billing attempt that
     * successfully completed after the current anchor date. To prevent fulfillment from being
     * pushed to the next anchor date, this field can override the billing attempt date.
     *
     * @return Carbon
     */
    public function getOriginTime(): ?Carbon
    {
        return $this->originTime;
    }

    
    /**
     * The reference shared between retried payment attempts.
     *
     * @return string
     */
    public function getPaymentGroupId(): ?string
    {
        return $this->paymentGroupId;
    }

    
    /**
     * The reference shared between payment attempts with similar payment details.
     *
     * @return string
     */
    public function getPaymentSessionId(): ?string
    {
        return $this->paymentSessionId;
    }

    
    /**
     * Error information from processing the billing attempt.
     *
     * @return ShopifySubscriptionBillingAttemptProcessingError
     */
    public function getProcessingError(): ?ShopifySubscriptionBillingAttemptProcessingError
    {
        return $this->processingError;
    }

    
    /**
     * Whether the billing attempt is still processing.
     *
     * @return bool
     */
    public function getReady(): ?bool
    {
        return $this->ready;
    }

    
    /**
     * Whether the billing attempt respects the merchant's inventory policy.
     *
     * @return bool
     */
    public function getRespectInventoryPolicy(): ?bool
    {
        return $this->respectInventoryPolicy;
    }

    
    /**
     * The subscription contract.
     *
     * @return ShopifySubscriptionContract
     */
    public function getSubscriptionContract(): ?ShopifySubscriptionContract
    {
        return $this->subscriptionContract;
    }

    
    /**
     * The transactions created by the billing attempt.
     *
     * @return ShopifyOrderTransactionConnection
     */
    public function getTransactions(): ?ShopifyOrderTransactionConnection
    {
        return $this->transactions;
    }

