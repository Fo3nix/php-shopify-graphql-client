     *
     * @deprecated Use `state` instead.
     */
    public function selectErrorCode(): static
    {
        $this->selectField("errorCode");

        return $this;
    }

    /**
     * A message describing a payment error during processing.
     *
     * @deprecated Use `state` instead.
     */
    public function selectErrorMessage(): static
    {
        $this->selectField("errorMessage");

        return $this;
    }

    /**
     * A globally-unique ID.
     */
    public function selectId(): static
    {
        $this->selectField("id");

        return $this;
    }

    /**
     * A unique key generated by the client to avoid duplicate payments.
     */
    public function selectIdempotencyKey(): static
    {
        $this->selectField("idempotencyKey");

        return $this;
    }

    /**
     * The URL where the customer needs to be redirected so they can complete the 3D Secure payment flow.
     *
     * @deprecated Use `state` instead.
     */
    public function selectNextActionUrl(): static
    {
        $this->selectField("nextActionUrl");

        return $this;
    }

