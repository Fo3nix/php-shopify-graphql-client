    public function selectProcessingError(?ShopifySubscriptionBillingAttemptProcessingErrorArgumentsObject $argsObject = null): ShopifySubscriptionBillingAttemptProcessingErrorInterfaceObject
    {
        $object = new ShopifySubscriptionBillingAttemptProcessingErrorInterfaceObject("processingError");
        if ($argsObject !== null) {
            $object->appendArguments($argsObject->toArray());
        }
        $this->selectField($object);

