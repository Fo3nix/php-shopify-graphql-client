     * Whether the billing attempt is still processing.
     *
     * @deprecated Use `state` instead.
     */
    public function selectReady(): static
    {
        $this->selectField("ready");

        return $this;
    }

    /**
     * Whether the billing attempt respects the merchant's inventory policy.
     */
    public function selectRespectInventoryPolicy(): static
    {
        $this->selectField("respectInventoryPolicy");

        return $this;
