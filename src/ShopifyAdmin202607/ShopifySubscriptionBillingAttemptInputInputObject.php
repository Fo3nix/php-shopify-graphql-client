<?php

namespace Fo3nix\ShopifyGraphQL\ShopifyAdmin202607;

use GraphQL\SchemaObject\InputObject;
use GraphQL\RawObject;

/**
 * The input fields required to complete a subscription billing attempt.
 */
class ShopifySubscriptionBillingAttemptInputInputObject extends InputObject
{
    const REQUIRED = ["idempotencyKey"];

    protected $actor;
    protected $idempotencyKey;
    protected $originTime;
    protected $billingCycleSelector;
    protected $paymentProcessingPolicy;
    protected $inventoryPolicy;

    /**
     * The actor who initiated a subscription action.
     */
    public function setActor($shopifySubscriptionActor): static
    {
        $this->actor = new RawObject($shopifySubscriptionActor);

        return $this;
    }

    /**
     * A unique key generated by the client to avoid duplicate payments. For more information, refer to [Idempotent requests](https://shopify.dev/api/usage/idempotent-requests).
     */
    public function setIdempotencyKey($idempotencyKey): static
    {
        $this->idempotencyKey = $idempotencyKey;

        return $this;
    }

    /**
     * The date and time used to calculate fulfillment intervals for a billing attempt that
     * successfully completed after the current anchor date. To prevent fulfillment from being
     * pushed to the next anchor date, this field can override the billing attempt date.
     */
    public function setOriginTime($originTime): static
    {
        $this->originTime = $originTime;

        return $this;
    }

    /**
     * Select the specific billing cycle to be billed.
     * Default to bill the current billing cycle if not specified.
     */
    public function setBillingCycleSelector(ShopifySubscriptionBillingCycleSelectorInputObject $shopifySubscriptionBillingCycleSelectorInputObject): static
    {
        $this->billingCycleSelector = $shopifySubscriptionBillingCycleSelectorInputObject;

        return $this;
    }

    /**
     * Select payment processing policy for the billing attempt. Defaults to FAIL_UNLESS_VALID_PAYMENT_METHOD.
     */
    public function setPaymentProcessingPolicy($shopifySubscriptionBillingAttemptPaymentProcessingPolicy): static
    {
        $this->paymentProcessingPolicy = new RawObject($shopifySubscriptionBillingAttemptPaymentProcessingPolicy);

        return $this;
    }

    /**
     * The behaviour to follow when creating an order for a product variant
     *       when it's out of stock.
     */
    public function setInventoryPolicy($shopifySubscriptionBillingAttemptInventoryPolicy): static
    {
        $this->inventoryPolicy = new RawObject($shopifySubscriptionBillingAttemptInventoryPolicy);

        return $this;
    }
}
