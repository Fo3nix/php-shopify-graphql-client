<?php

namespace Fo3nix\ShopifyGraphQL\ShopifyAdmin202610;

use GraphQL\SchemaObject\QueryObject;

/**
 * Store usage for app subscriptions with usage pricing.
 */
class ShopifyAppUsageRecordQueryObject extends QueryObject
{
    const OBJECT_NAME = "AppUsageRecord";

    /**
     * The date and time when the usage record was created.
     */
    public function selectCreatedAt(): static
    {
        $this->selectField("createdAt");

        return $this;
    }

    /**
     * The description of the app usage record.
     */
    public function selectDescription(): static
    {
        $this->selectField("description");

        return $this;
    }

    /**
     * A globally-unique ID.
     */
    public function selectId(): static
    {
        $this->selectField("id");

        return $this;
    }

    /**
     * A unique key generated by the client to avoid duplicate charges.
     */
    public function selectIdempotencyKey(): static
    {
        $this->selectField("idempotencyKey");

        return $this;
    }

    /**
     * The price of the usage record.
     */
    public function selectPrice(?ShopifyAppUsageRecordPriceArgumentsObject $argsObject = null): ShopifyMoneyV2QueryObject
    {
        $object = new ShopifyMoneyV2QueryObject("price");
        if ($argsObject !== null) {
            $object->appendArguments($argsObject->toArray());
        }
        $this->selectField($object);

        return $object;
    }

    /**
     * Defines the usage pricing plan the merchant is subscribed to.
     */
    public function selectSubscriptionLineItem(?ShopifyAppUsageRecordSubscriptionLineItemArgumentsObject $argsObject = null): ShopifyAppSubscriptionLineItemQueryObject
    {
        $object = new ShopifyAppSubscriptionLineItemQueryObject("subscriptionLineItem");
        if ($argsObject !== null) {
            $object->appendArguments($argsObject->toArray());
        }
        $this->selectField($object);

        return $object;
    }
}
