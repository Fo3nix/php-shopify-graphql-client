<?php

namespace Fo3nix\ShopifyGraphQL\ShopifyAdmin202610;

use Carbon\Carbon;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202610\ShopifyMoneyV2;
use Fo3nix\ShopifyGraphQL\ShopifyAdmin202610\ShopifyAppSubscriptionLineItem;

/**
 * Store usage for app subscriptions with usage pricing.
 */
class ShopifyAppUsageRecord implements ShopifyNode
{
    protected $createdAt;
    protected $description;
    protected $id;
    protected $idempotencyKey;
    protected $price;
    protected $subscriptionLineItem;

    
    /**
     * The date and time when the usage record was created.
     *
     * @return Carbon
     */
    public function getCreatedAt(): ?Carbon
    {
        return $this->createdAt;
    }

    
    /**
     * The description of the app usage record.
     *
     * @return string
     */
    public function getDescription(): ?string
    {
        return $this->description;
    }

    
    /**
     * A globally-unique ID.
     *
     * @return string
     */
    public function getId(): ?string
    {
        return $this->id;
    }

    
    /**
     * A unique key generated by the client to avoid duplicate charges.
     *
     * @return string
     */
    public function getIdempotencyKey(): ?string
    {
        return $this->idempotencyKey;
    }

    
    /**
     * The price of the usage record.
     *
     * @return ShopifyMoneyV2
     */
    public function getPrice(): ?ShopifyMoneyV2
    {
        return $this->price;
    }

    
    /**
     * Defines the usage pricing plan the merchant is subscribed to.
     *
     * @return ShopifyAppSubscriptionLineItem
     */
    public function getSubscriptionLineItem(): ?ShopifyAppSubscriptionLineItem
    {
        return $this->subscriptionLineItem;
    }

        /**
         * @param array $data
         * @return self
         */
        public static function fromArray(array $data): self
        {
            $instance = new self();
            if (isset($data['createdAt']) && $data['createdAt'] !== null) {
                $instance->createdAt = new Carbon($data['createdAt']);
            }
            if (isset($data['description']) && $data['description'] !== null) {
                $instance->description = $data['description'];
            }
            if (isset($data['id']) && $data['id'] !== null) {
                $instance->id = $data['id'];
            }
            if (isset($data['idempotencyKey']) && $data['idempotencyKey'] !== null) {
                $instance->idempotencyKey = $data['idempotencyKey'];
            }
            if (isset($data['price']) && $data['price'] !== null) {
                $instance->price = ShopifyMoneyV2::fromArray($data['price']);
            }
            if (isset($data['subscriptionLineItem']) && $data['subscriptionLineItem'] !== null) {
                $instance->subscriptionLineItem = ShopifyAppSubscriptionLineItem::fromArray($data['subscriptionLineItem']);
            }
            return $instance;
        }

        /**
         * @param string $json
         * @return self
         */
        public static function fromJson(string $json): self
        {
            $data = json_decode($json, true);
            if ($data === null && json_last_error() !== JSON_ERROR_NONE) {
                throw new \InvalidArgumentException('Invalid JSON provided to fromJson method: ' . json_last_error_msg());
            }
            return self::fromArray($data);
        }

        /**
         * Converts this object to an array.
         * @return array
         */
        public function asArray(): array
        {
            $data = [];
            if ($this->createdAt !== null) {
                $data['createdAt'] = $this->createdAt->toIso8601String();
            }
            if ($this->description !== null) {
                $data['description'] = $this->description;
            }
            if ($this->id !== null) {
                $data['id'] = $this->id;
            }
            if ($this->idempotencyKey !== null) {
                $data['idempotencyKey'] = $this->idempotencyKey;
            }
            if ($this->price !== null) {
                $data['price'] = $this->price->asArray();
            }
            if ($this->subscriptionLineItem !== null) {
                $data['subscriptionLineItem'] = $this->subscriptionLineItem->asArray();
            }
            return $data;
        }
}
